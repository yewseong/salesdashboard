// Helper to compute 12-Month Forecast
export function generate12MonthForecast(
  historical: MonthlyRevenueRecord[],
  controls: ForecastControls
): ForecastMonth[] {
  const months = [
    { short: 'Oct 26', full: 'October 2026', year: 2026, seasonality: 1.02 },
    { short: 'Nov 26', full: 'November 2026', year: 2026, seasonality: 1.05 },
    { short: 'Dec 26', full: 'December 2026', year: 2026, seasonality: 1.15 },
    { short: 'Jan 27', full: 'January 2027', year: 2027, seasonality: 0.94 },
    { short: 'Feb 27', full: 'February 2027', year: 2027, seasonality: 0.98 },
    { short: 'Mar 27', full: 'March 2027', year: 2027, seasonality: 1.08 },
    { short: 'Apr 27', full: 'April 2027', year: 2027, seasonality: 1.01 },
    { short: 'May 27', full: 'May 2027', year: 2027, seasonality: 1.04 },
    { short: 'Jun 27', full: 'June 2027', year: 2027, seasonality: 1.12 },
    { short: 'Jul 27', full: 'July 2027', year: 2027, seasonality: 0.96 },
    { short: 'Aug 27', full: 'August 2027', year: 2027, seasonality: 1.00 },
    { short: 'Sep 27', full: 'September 2027', year: 2027, seasonality: 1.14 },
  ];

  // Starting base from latest months
  const lastBase = 930000;
  const targetBase = 980000;

  let currentBaseline = lastBase;
  let currentTarget = targetBase;

  return months.map((m, index) => {
    // Compound growth
    const monthlyGrowth = 1 + controls.growthRatePct / 100;
    const churnDampener = 1 - controls.churnRatePct / 100;
    const winRateEffect = 1 + controls.winRateAdjustmentPct / 100;

    currentBaseline = currentBaseline * monthlyGrowth * churnDampener * winRateEffect;
    currentTarget = currentTarget * 1.022; // Target grows approx 2.2% monthly

    const baselineSeasoned = Math.round(currentBaseline * m.seasonality);
    const targetSeasoned = Math.round(currentTarget * m.seasonality);

    // Scenario calculation
    let scenarioMultiplier = 1.0;
    if (controls.scenario === 'conservative') scenarioMultiplier = 0.88;
    if (controls.scenario === 'optimistic') scenarioMultiplier = 1.16;

    const expected = Math.round(baselineSeasoned * scenarioMultiplier);
    const conservative = Math.round(baselineSeasoned * 0.86);
    const optimistic = Math.round(baselineSeasoned * 1.18);
    const weightedPipeline = Math.round(expected * 0.72);
    
    // Confidence score decays slightly over time as forecasting further into the future
    const confidenceScore = Math.max(50, Math.round(92 - index * 3.2));

    return {
      month: m.full,
      monthShort: m.short,
      year: m.year,
      expectedRevenue: expected,
      conservativeRevenue: conservative,
      optimisticRevenue: optimistic,
      targetRevenue: targetSeasoned,
      weightedPipeline,
      confidenceScore,
    };
  });
}

